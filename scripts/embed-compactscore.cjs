/* Run with @babel/core and @babel/preset-env installed; embeds all code in the updater's single QML. */
const fs=require('fs'),path=require('path');
const babel=require('@babel/core'),preset=require('@babel/preset-env');
const dir=path.resolve(__dirname,'..'),qml=path.join(dir,'AI-Notation-Studio-App.qml');
let source='var scope = {};\n';
for(const file of ['compactscore.js','compactscore-musicxml.js','compactscore-costs.js']) {
 let code=fs.readFileSync(path.join(dir,file),'utf8');
 code=code.replace(/\}\)\(typeof globalThis!==?'undefined'\?globalThis:this\);?\s*$/, '})(scope);');
 code=code.replace(/Object\.fromEntries/g,'csFromEntries').replace(/Object\.entries/g,'csEntries');
 source+=code+'\n';
}
source+='return { score:scope.CompactScore, xml:scope.CompactMusicXML, ai:scope.CompactAI };';
source=`function csEntries(o) { return Object.keys(o).map(function(k){return [k,o[k]];}); }
function csFromEntries(a) { var o={}; a.forEach(function(e){Object.defineProperty(o,e[0],{value:e[1],enumerable:true,writable:true,configurable:true});}); return o; }
`+source;
const output=babel.transformSync(source,{parserOpts:{allowReturnOutsideFunction:true},presets:[[preset,{targets:{ie:'11'},modules:false}]],comments:false,compact:false}).code;
const block='    // BEGIN COMPACTSCORE RUNTIME (generated by scripts/embed-compactscore.cjs)\n    function createCompactRuntime() {\n'+output.split('\n').map(l=>l?'        '+l:'').join('\n')+'\n    }\n    // END COMPACTSCORE RUNTIME\n';
let app=fs.readFileSync(qml,'utf8');
const begin=app.indexOf('    // BEGIN COMPACTSCORE RUNTIME'),end=app.indexOf('    // END COMPACTSCORE RUNTIME');
if(begin>=0)app=app.slice(0,begin)+block+app.slice(end+'    // END COMPACTSCORE RUNTIME\n'.length);else app=app.replace('    function currentVersionString()',block+'\n    function currentVersionString()');
fs.writeFileSync(qml,app);
